"""Extracts the erfcx_y100 Chebyshev table from PyTorch's ATen/native/Math.h
(itself from the Faddeeva package, MIT licensed, S. G. Johnson) into
csrc/kernels/erfcx_table.inc.

    python scripts/gen_erfcx_table.py
"""
import os
import re

import torch

src = open(os.path.join(os.path.dirname(torch.__file__), "include/ATen/native/Math.h")).read()
start = src.index("erfcx_y100(T y100)")
body = src[start:src.index("return 1.0;", start)]
cases = re.findall(r"case (\d+): \{\s*T t = 2\*y100 - (\d+);\s*return (.*?);\s*\}", body, re.S)
assert len(cases) == 100
rows = []
for k, off, expr in cases:
    nums = re.findall(r"[0-9.]+e[-+]?\d+", expr)
    assert int(off) == 2 * int(k) + 1 and len(nums) == 7
    rows.append("    {" + ", ".join(nums) + "},")
out = os.path.join(os.path.dirname(__file__), "..", "csrc/kernels/erfcx_table.inc")
with open(out, "w") as f:
    f.write("// Generated by scripts/gen_erfcx_table.py from ATen/native/Math.h (Faddeeva package,\n"
            "// MIT license). Row k: coefficients c0..c6 of erfcx_y100 on [k, k+1), t = 2*y100 - (2k+1).\n")
    f.write("\n".join(rows) + "\n")
print("wrote", out)
