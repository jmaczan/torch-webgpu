"""Inductor (torch.compile) backend for the webgpu device: fused WGSL
kernels generated by torch_webgpu._inductor.wgsl."""

from __future__ import annotations

from collections import namedtuple
from typing import Any

import torch

_registered = False


def register() -> None:
    global _registered
    if _registered:
        return
    _registered = True

    from torch._dynamo.device_interface import DeviceInterface, register_interface_for_device
    from torch._inductor.codegen.common import (
        DeviceOpOverrides,
        register_backend_for_device,
        register_device_op_overrides,
    )
    from torch._inductor.codegen.wrapper import PythonWrapperCodegen

    from .wgsl import WGSLScheduling

    class WebGPUInterface(DeviceInterface):
        @staticmethod
        def is_gpu() -> bool:
            return True

        @staticmethod
        def is_bf16_supported(including_emulation: bool = False) -> bool:
            return True

        @classmethod
        def is_dtype_supported(cls, dtype: torch.dtype, including_emulation: bool = False) -> bool:
            return dtype not in (torch.float64, torch.complex64, torch.complex128)

        @staticmethod
        def is_available() -> bool:
            return torch.webgpu.is_available()

        @staticmethod
        def device_count() -> int:
            return torch.webgpu.device_count()

        @staticmethod
        def current_device() -> int:
            return 0

        @staticmethod
        def set_device(device: Any) -> None:
            pass

        @staticmethod
        def get_compute_capability(device: Any = None) -> str:
            return ""

        @staticmethod
        def synchronize(device: Any = None) -> None:
            torch.webgpu.synchronize()

        class Worker:
            @staticmethod
            def get_device_properties(device: Any = None) -> Any:
                # WebGPU does not expose the number of compute units; this is
                # only used by split-reduction heuristics.
                return namedtuple("WebGPUProperties", ["multi_processor_count"])(64)

            @staticmethod
            def current_device() -> int:
                return 0

    class WebGPUDeviceOpOverrides(DeviceOpOverrides):
        def device_guard(self, device_idx: Any) -> str:
            return "torch._ops.contextlib.nullcontext()"

        def set_device(self, device_idx: Any) -> str:
            return "pass  # webgpu set device"

        def synchronize(self) -> str:
            return "torch.webgpu.synchronize()"

    class WebGPUWrapperCodegen(PythonWrapperCodegen):
        @staticmethod
        def create(is_subgraph: bool, subgraph_name: Any, parent_wrapper: Any, partition_signatures: Any = None):
            if is_subgraph:
                from torch._inductor.codegen.wrapper import SubgraphPythonWrapperCodegen

                return SubgraphPythonWrapperCodegen(subgraph_name, parent_wrapper, partition_signatures)
            return WebGPUWrapperCodegen()

        def _generate_kernel_call_helper(self, kernel_name: str, call_args: Any, *, device: Any = None,
                                         triton: bool = True, **kwargs: Any) -> None:
            device = device or V.graph.get_current_device_or_throw()
            if not triton and device.type == "webgpu":
                self.writeline(self.wrap_kernel_call(kernel_name, call_args))
                return
            super()._generate_kernel_call_helper(kernel_name, call_args, device=device, triton=triton, **kwargs)

    from torch._inductor.virtualized import V  # noqa: F401  (used above)

    from torch._inductor.custom_graph_pass import CustomGraphModulePass

    class BackendVersion(CustomGraphModulePass):
        """No-op pass whose uuid puts this backend's code generator (and the
        WGSL helpers it embeds) into Inductor's FX graph cache key, so cached
        graphs are invalidated when the backend changes."""

        def __call__(self, gm: torch.fx.GraphModule) -> None:
            pass

        def uuid(self) -> Any:
            return _backend_hash()

    _fallback_unsupported_dtypes()
    register_interface_for_device("webgpu", WebGPUInterface)
    register_device_op_overrides("webgpu", WebGPUDeviceOpOverrides())
    register_backend_for_device("webgpu", WGSLScheduling, WebGPUWrapperCodegen, device_custom_pass=BackendVersion())


# Dtypes WGSL kernels can't compute in. Graph nodes reading or writing them
# on webgpu become eager aten calls (where float64 runs through the CPU
# fallback), as Inductor does for complex tensors.
UNSUPPORTED_DTYPES = (torch.float64,)

# aten ops whose pointwise math has no WGSL implementation yet: they run as
# eager calls (as in eager mode, through the CPU fallback).
FALLBACK_OPS = frozenset(
    [f"special_{n}" for n in (
        "airy_ai", "bessel_j0", "bessel_j1", "bessel_y0", "bessel_y1", "modified_bessel_i0",
        "modified_bessel_i1", "modified_bessel_k0", "modified_bessel_k1", "scaled_modified_bessel_k0",
        "scaled_modified_bessel_k1", "spherical_bessel_j0", "hermite_polynomial_h", "hermite_polynomial_he",
        "laguerre_polynomial_l", "legendre_polynomial_p",
        *(f"{s}chebyshev_polynomial_{k}" for s in ("", "shifted_") for k in "tuvw"))]
    + ["igamma", "igammac"]
)


def _needs_eager(t: torch.Tensor, node: Any) -> bool:
    if t.device.type != "webgpu":
        return False
    if t.dtype in UNSUPPORTED_DTYPES:
        return True
    target = getattr(node, "target", None)
    name = getattr(getattr(target, "_overloadpacket", None), "__name__", None)
    if name in FALLBACK_OPS:
        return True
    # nextafter steps the float32 representation only.
    return name == "nextafter" and t.dtype != torch.float32


def _fallback_unsupported_dtypes() -> None:
    from torch._inductor import lowering

    orig = lowering.unsupported_input_tensor

    def unsupported_input_tensor(t: torch.Tensor, node: Any = None) -> bool:
        return _needs_eager(t, node) or orig(t, node)

    lowering.unsupported_input_tensor = unsupported_input_tensor


_hash: str | None = None


def _backend_hash() -> str:
    global _hash
    if _hash is None:
        import hashlib
        from pathlib import Path

        from .. import _C

        h = hashlib.sha256()
        for f in sorted(Path(__file__).parent.glob("*.py")):
            h.update(f.read_bytes())
        h.update(_C._wgsl_prelude().encode())
        h.update(_C._wgsl_math().encode())
        _hash = h.hexdigest()
    return _hash
